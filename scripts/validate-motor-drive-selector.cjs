'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const root='portal/src/main/resources/static/';
const selector=require('../portal/src/main/resources/static/motor-drive-selector.js');
const check=(x)=>{const r=selector.compute(x);assert.equal(r.valid,true,JSON.stringify(r.errors));return r;};
const method=(r,id)=>{const x=r.methods.find(m=>m.id===id);assert.ok(x,'Expected method '+id);return x;};
let cases=0;
const base={family:'ac_induction_3',supply:'ac3',volts:600,motorVolts:575,fla:20,
  startsHour:2,startSeconds:8,load:'light',goal:'simple',leads:'3'};
let r=check(base);assert.equal(method(r,'dol').status,'eligible');
assert.equal(method(r,'vfd').status,'eligible');
assert.equal(method(r,'wye_delta').status,'not_suitable');
assert.equal(r.recommendations[0].id,'dol');
assert.equal(r.calculations.nameplateFLA,20);
assert.equal(r.calculations.continuousOutputMinimumA,20);cases++;
r=check({...base,goal:'inrush',leads:'6',deltaVolts:600,lraMultiple:6});
assert.equal(method(r,'wye_delta').status,'eligible');
assert.equal(r.calculations.suppliedLraA,120);
assert.equal(r.calculations.idealWyeDeltaStartingLineA,40);
assert.equal(r.calculations.insideDeltaWindingA,Number((20/Math.sqrt(3)).toFixed(2)));
assert.equal(r.recommendations[0].id,'soft');cases++;
r=check({...base,leads:'6',deltaVolts:400});
assert.equal(method(r,'wye_delta').status,'not_suitable');cases++;
r=check({...base,leads:'6',deltaVolts:600,load:'heavy',goal:'torque'});
assert.equal(method(r,'wye_delta').status,'conditional');
assert.equal(method(r,'soft').status,'conditional');
assert.equal(r.recommendations[0].id,'vfd');cases++;
r=check({...base,goal:'variable'});
assert.equal(r.recommendations[0].id,'vfd');cases++;
r=check({...base,goal:'reverse',reversing:true});
assert.equal(r.recommendations[0].id,'reversing');cases++;
r=check({...base,startsHour:32,startSeconds:30});
assert.ok(r.warnings.some(x=>x.includes('Frequent or extended starts')));cases++;
r=check({...base,supply:'ac1'});assert.equal(method(r,'vfd').status,'conditional');
assert.equal(method(r,'dol').status,'not_suitable');cases++;
r=check({family:'ac_cap_start_1',supply:'ac1',volts:240,motorVolts:240,fla:8,startsHour:2,startSeconds:4});
assert.equal(method(r,'cap').status,'eligible');assert.equal(method(r,'wye_delta').status,'not_suitable');
assert.equal(method(r,'vfd').status,'conditional');cases++;
r=check({family:'ac_cap_run_1',supply:'ac1',volts:120,motorVolts:120,fla:5,startsHour:2,startSeconds:3});
assert.equal(method(r,'psc').status,'eligible');cases++;
r=check({family:'dc_pm',supply:'dc',volts:180,motorVolts:180,fla:30,startsHour:5,startSeconds:6,goal:'variable'});
assert.equal(method(r,'dc_drive').status,'eligible');assert.equal(method(r,'vfd').status,'not_suitable');
assert.equal(r.calculations.nominalDcKw,5.4);cases++;
r=check({family:'dc_series',supply:'dc',volts:180,motorVolts:180,fla:30,startsHour:5,startSeconds:6});
assert.ok(r.warnings.some(x=>x.includes('overspeed')));cases++;
r=check({family:'dc_bldc',supply:'dc',volts:48,motorVolts:48,fla:10,startsHour:5,startSeconds:6});
assert.equal(method(r,'brushless').status,'eligible');assert.equal(method(r,'dol').status,'not_suitable');cases++;
r=check({family:'ac_synchronous_3',supply:'ac3',volts:600,motorVolts:575,fla:20,startsHour:2,startSeconds:6});
assert.equal(method(r,'wye_delta').status,'not_suitable');
assert.equal(method(r,'vfd').status,'conditional');cases++;
r=check({...base,volts:600,motorVolts:230});
assert.equal(method(r,'dol').status,'not_suitable');
assert.equal(method(r,'soft').status,'not_suitable');
assert.equal(method(r,'vfd').status,'conditional');cases++;
r=check({...base,candidateAmps:30,deratingPct:80});
assert.equal(r.calculations.afterDeratingCurrentA,24);
assert.equal(r.calculations.candidatePassesContinuousFLA,true);cases++;
r=check({...base,candidateAmps:22,deratingPct:80});
assert.equal(r.calculations.candidatePassesContinuousFLA,false);
assert.ok(r.warnings.some(x=>x.includes('FAILS continuous-current screening')));cases++;
r=check({...base,lraMultiple:6,leads:'3'});
assert.equal(r.calculations.idealWyeDeltaStartingLineA,null);cases++;
for(const x of [{...base,fla:0},{...base,motorVolts:0},{...base,startsHour:0},{...base,startSeconds:-1},{...base,hp:-5},{...base,lraMultiple:-6},{...base,deltaVolts:-600},{...base,candidateAmps:-2},{...base,deratingPct:120},{...base,family:'unknown'}]){
 assert.equal(selector.compute(x).valid,false,'Invalid input accepted: '+JSON.stringify(x));cases++;
}
const html=fs.readFileSync(root+'motor-starter-selector.html','utf8');
const catalog=fs.readFileSync(root+'tool-catalog.js','utf8');
assert.ok(html.includes('/workbench-themes.css')&&html.includes('/workbench-theme.js'));
for(const str of ['motor-drive-selector.js','motorVolts','startsHour','deltaVolts','fla','Export selection JSON','JSON.stringify(payload,null,2)','candidateAmps','deratingPct'])
 assert.ok(html.includes(str),'Missing UI: '+str);
assert.ok(catalog.includes('"motor-drive-select"')&&catalog.includes('/motor-starter-selector.html'));
assert.ok(fs.readFileSync('android-client/app/src/main/java/com/gfh/electricalworkbench/MobileToolFinder.kt','utf8').includes('MobileTask("motor-drive-select"'));
assert.ok(fs.readFileSync('ios-client/ElectricalWorkbench/WorkbenchTools.swift','utf8').includes('id: "motor-drive-select"'));
assert.ok(fs.readFileSync('desktop-client/src/main/java/com/example/desktop/ElectricalWorkbenchNativeApp.java','utf8').includes('tile("⚙ Motor Starter & Drive Selector"'));
console.log('PASS: '+cases+' AC/DC starter selection, validation, duty, motor family and cross-platform routes tested.');
